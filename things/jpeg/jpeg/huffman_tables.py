"""The standard JPEG Huffman tables (ITU-T.81 Annex K.3), the same
default tables essentially every baseline JPEG encoder ships instead of
computing optimal tables per image. Each table is specified in the
spec's own format: BITS[1..16] (how many codes of each bit length exist)
plus HUFFVAL (the symbols, in the order codes get assigned).

generate_codes() turns (BITS, HUFFVAL) into actual bit-strings using the
exact procedure in Annex C ("Generate_size_table" + "Generate_code_table"):
walk the symbols in HUFFVAL order, assign codes of non-decreasing length,
and left-shift (increment length, effectively appending a 0 bit and then
counting up) every time the length increases. This is also exactly the
procedure a decoder uses to reconstruct the same table from the same
(BITS, HUFFVAL) pair written into the file's DHT segment, which is what
makes writer.py emitting BITS/HUFFVAL (not the codes themselves) into the
file both correct and standard practice.
"""
from __future__ import annotations


def generate_codes(bits: list, huffval: list) -> dict:
    """bits: 16 ints, bits[i] = count of codes with length i+1.
    huffval: symbols in code-assignment order (len(huffval) == sum(bits)).
    Returns {symbol: (code_int, code_length)}.
    """
    sizes = []
    for length, count in enumerate(bits, start=1):
        sizes.extend([length] * count)
    assert len(sizes) == len(huffval), "BITS total must match HUFFVAL count"

    codes = []
    code = 0
    size = sizes[0] if sizes else 0
    for i, sz in enumerate(sizes):
        while size < sz:
            code <<= 1
            size += 1
        codes.append(code)
        code += 1

    return {sym: (codes[i], sizes[i]) for i, sym in enumerate(huffval)}


